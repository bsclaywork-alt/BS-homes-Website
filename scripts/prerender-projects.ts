/**
 * scripts/prerender-projects.ts
 * Pre-renders static HTML pages for every project at dist/projects/<slug>/index.html
 * ensuring true HTTP 200 responses and unique SEO metadata on GitHub Pages.
 */

import fs from 'fs';
import path from 'path';
import { 
  SITEMAP_PROJECTS, 
  SitemapProjectItem, 
  generatePropertyMetaTags, 
  slugify 
} from '../src/data/projectsSitemapData';
import { fetchActiveDbProjects, mergeProjects } from './update-sitemap';

function escapeHtml(str: string): string {
  if (!str) return '';
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}

export async function prerenderProjects() {
  console.log('[Project Prerender] Starting static project detail page generation...');

  const distDir = path.resolve(process.cwd(), 'dist');
  const templatePath = path.join(distDir, 'index.html');

  if (!fs.existsSync(templatePath)) {
    console.error('[Project Prerender Error] dist/index.html not found. Run vite build first.');
    process.exit(1);
  }

  const baseTemplate = fs.readFileSync(templatePath, 'utf-8');

  // 1. Fetch Firestore projects with robust fallback
  let dbProjects: SitemapProjectItem[] = [];
  let dbFetchSuccess = true;
  try {
    dbProjects = await fetchActiveDbProjects();
  } catch (err) {
    dbFetchSuccess = false;
    console.warn('[Project Prerender Warning] Firestore fetch failed; dynamic projects omitted, falling back to curated baseline data:', err);
  }

  // 2. Merge curated baseline and Firestore projects
  const allProjects = mergeProjects(SITEMAP_PROJECTS, dbProjects);
  const curatedCount = SITEMAP_PROJECTS.length;
  const dbCount = dbProjects.length;

  console.log(`[Project Prerender] Merged dataset: ${allProjects.length} total projects (${curatedCount} curated, ${dbCount} from Firestore). Firestore status: ${dbFetchSuccess ? 'Success' : 'Fallback / Omitted'}`);

  const baseUrl = 'https://bshomez.in';
  const usedSlugs = new Set<string>();
  let generatedCount = 0;
  let collisionCount = 0;
  const skippedProjects: Array<{ name: string; reason: string }> = [];

  for (const project of allProjects) {
    if (!project.name) {
      skippedProjects.push({ name: project.id || 'Unknown', reason: 'Missing project name' });
      continue;
    }

    let slug = slugify(project.name);
    if (!slug) {
      skippedProjects.push({ name: project.name, reason: 'Invalid or empty slug' });
      continue;
    }

    // Slug collision check
    if (usedSlugs.has(slug)) {
      collisionCount++;
      const uniqueSuffix = slugify(project.id || Math.random().toString(36).substring(2, 7));
      slug = `${slug}-${uniqueSuffix}`;
      console.warn(`[Project Prerender Collision] Duplicate slug detected for "${project.name}". Resolved to unique slug: "${slug}"`);
    }
    usedSlugs.add(slug);

    // Generate SEO metadata
    const meta = generatePropertyMetaTags(project, baseUrl);
    const projectDir = path.join(distDir, 'projects', slug);
    if (!fs.existsSync(projectDir)) {
      fs.mkdirSync(projectDir, { recursive: true });
    }

    let html = baseTemplate;

    // HTML-escape dynamic meta tags
    const safeTitle = escapeHtml(meta.title);
    const safeDesc = escapeHtml(meta.description);
    const safeCanonical = escapeHtml(meta.canonical);
    const safeOgTitle = escapeHtml(meta.ogTitle);
    const safeOgDesc = escapeHtml(meta.ogDescription);
    const safeOgUrl = escapeHtml(meta.ogUrl);
    const safeOgImage = escapeHtml(meta.ogImage || 'https://bshomez.in/og-cover.jpg');

    html = html.replace(/<title>[\s\S]*?<\/title>/i, `<title>${safeTitle}</title>`);
    html = html.replace(/<meta\s+name="description"\s+content="[\s\S]*?"\s*\/?>/i, `<meta name="description" content="${safeDesc}" />`);
    html = html.replace(/<link\s+rel="canonical"\s+href="[\s\S]*?"\s*\/?>/i, `<link rel="canonical" href="${safeCanonical}" />`);
    html = html.replace(/<meta\s+property="og:title"\s+content="[\s\S]*?"\s*\/?>/i, `<meta property="og:title" content="${safeOgTitle}" />`);
    html = html.replace(/<meta\s+property="og:description"\s+content="[\s\S]*?"\s*\/?>/i, `<meta property="og:description" content="${safeOgDesc}" />`);
    html = html.replace(/<meta\s+property="og:url"\s+content="[\s\S]*?"\s*\/?>/i, `<meta property="og:url" content="${safeOgUrl}" />`);
    html = html.replace(/<meta\s+property="og:image"\s+content="[\s\S]*?"\s*\/?>/i, `<meta property="og:image" content="${safeOgImage}" />`);

    const propertyJsonLdSnippet = `
    <!-- Google Rich Results Structured Data for Property (Generated by BS Homez Prerender) -->
    <script type="application/ld+json" id="property-jsonld">
      ${meta.schemaJson}
    </script>
  </head>`;
    html = html.replace(/<\/head>/i, propertyJsonLdSnippet);

    fs.writeFileSync(path.join(projectDir, 'index.html'), html, 'utf-8');
    generatedCount++;
  }

  console.log('========================================');
  console.log('[Project Prerender Summary]');
  console.log(`- Total Project HTML Pages Generated: ${generatedCount}`);
  console.log(`- Curated Baseline Projects: ${curatedCount}`);
  console.log(`- Firestore Active Projects: ${dbCount} (${dbFetchSuccess ? 'Loaded Successfully' : 'Omitted / Fallback Active'})`);
  console.log(`- Slug Collisions Handled: ${collisionCount}`);
  console.log(`- Skipped Projects: ${skippedProjects.length}`);
  if (skippedProjects.length > 0) {
    console.log('  Skipped details:', skippedProjects);
  }
  console.log('========================================');

  return {
    success: true,
    generatedCount,
    curatedCount,
    dbCount,
    collisionCount,
    skippedProjects
  };
}

const isDirectExecution = process.argv[1] && process.argv[1].includes('prerender-projects');
if (isDirectExecution) {
  prerenderProjects().then((res) => {
    process.exit(res.success ? 0 : 1);
  });
}
